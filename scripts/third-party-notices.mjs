// `node scripts/third-party-notices.mjs`: writes THIRD-PARTY-NOTICES.md, the Rust crates and npm
// packages a Nitely build ships, with each one's license. Rust: what `cargo tree` reaches over
// normal edges (no dev or build dependencies) from the app and the CLI, for every target. npm: the
// production packages in package-lock.json, which Vite bundles into the frontend. Run it again
// when dependencies change; the release build (NIT-92) runs it and ships each license's text.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const rows = new Map();
const add = (kind, name, version, license, source) => {
  const key = `${kind} ${name} ${version}`;
  if (!rows.has(key)) rows.set(key, { kind, name, version, license: license || "see its repository", source: source || "" });
};

const tree = execFileSync(
  "cargo",
  ["tree", "--locked", "-e", "normal", "--target", "all", "--prefix", "none", "-p", "nitely-app", "-p", "nitely-cli", "--format", "{p}\t{l}\t{r}"],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);
for (const line of tree.split("\n")) {
  const [pkg, license, repo = ""] = line.trim().split("\t");
  if (!pkg) continue;
  // "name v1.2.3", "name v1.2.3 (proc-macro)" or "name v1.2.3 (path)": the workspace's own crates
  // have a path, and proc macros run at build time only, so neither ships.
  const m = pkg.match(/^(\S+) v(\S+)(.*)$/);
  if (!m || m[3].includes("(")) continue;
  add("Rust", m[1], m[2], license, repo.replace(/ \(\*\)$/, ""));
}

const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
for (const [path, p] of Object.entries(lock.packages)) {
  if (!path || p.dev || p.devOptional) continue;
  const name = path.replace(/^.*node_modules\//, "");
  const pkg = JSON.parse(readFileSync(`${path}/package.json`, "utf8"));
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  add("npm", name, p.version, p.license ?? pkg.license, repo?.replace(/^git\+/, "").replace(/\.git$/, ""));
}

const sorted = [...rows.values()].sort((a, b) => a.kind.localeCompare(b.kind) || a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const byLicense = new Map();
for (const r of sorted) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);

const out = [
  "# Third-party notices",
  "",
  "Nitely is licensed under the Apache License 2.0 (LICENSE, NOTICE). A Nitely build also ships the",
  "open-source packages below, each under its own license. Generated by",
  "`node scripts/third-party-notices.mjs` from Cargo.lock and package-lock.json: every crate the app",
  "and the CLI reach over normal dependencies on any target (a superset of what one build ships),",
  "and every production npm package.",
  "",
  "Licenses that ask more than a notice:",
  "",
  "- **MPL-2.0** (cssparser, selectors and others): file-level copyleft. Nitely uses these crates",
  "  unmodified from crates.io, where their source is; a change to one of their files must be shared",
  "  under MPL-2.0.",
  "- **OFL-1.1** (the Geist and Geist Mono fonts): the fonts may be bundled and redistributed with",
  "  their license, and may not be sold on their own.",
  "",
  "## By license",
  "",
  "| License | Packages |",
  "| --- | --- |",
  ...[...byLicense.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`),
  "",
  "## Packages",
  "",
  "| | Package | Version | License | Source |",
  "| --- | --- | --- | --- | --- |",
  ...sorted.map((r) => `| ${r.kind} | ${r.name} | ${r.version} | ${r.license} | ${r.source} |`),
  "",
];
writeFileSync("THIRD-PARTY-NOTICES.md", out.join("\n"));
console.log(`THIRD-PARTY-NOTICES.md: ${sorted.length} packages`);
